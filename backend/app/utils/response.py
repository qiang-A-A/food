# =============================================================================
# app/utils/response.py — 统一响应信封工具
# -----------------------------------------------------------------------------
# 功能：封装成功响应信封 {code:0, message, data}（对应开发技术文档 §6 统一约定），
#       所有路由通过 ok() 返回，保证前端拆包逻辑一致。
# =============================================================================

from typing import Any


def ok(data: Any = None, message: str = "success") -> dict:
    """构造成功响应信封。"""
    return {"code": 0, "message": message, "data": data}
